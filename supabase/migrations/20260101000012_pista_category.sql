-- =============================================================
-- カテゴリ「シティサイクル」を「ピストバイク」に置き換える
--
-- 甲の指定による取扱い車種の変更。表示名だけでなく、
-- listings.category に入る値そのものを city から pista へ移す。
-- 値を city のままにすると、コード上は「シティサイクル」と読めるのに
-- 実際はピストバイクを指すことになり、検索の読み替えも噛み合わなくなる。
--
-- ただし、すでに city で出されている商品はシティサイクルであって
-- ピストバイクではない。pista へ付け替えると実物と違うカテゴリになるため、
-- 「その他」へ寄せる。選べる区分が無くなっただけで、商品自体は変わらない。
--
-- category に check 制約は無いため、既存行の付け替えだけで足りる。
-- 何度流しても同じ結果になる。
-- =============================================================
update public.listings set category = 'other' where category = 'city';
